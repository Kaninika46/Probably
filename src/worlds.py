"""Stretch item (CLAUDE.md section 7.8): possible-worlds Monte Carlo sampler.

In a Block-Independent-Disjoint (BID) probabilistic database, one "possible world"
is generated by independently choosing exactly one segment for each customer i
according to their block probability vector (p_{i,1}, ..., p_{i,K}).

We draw M = 10,000 possible worlds (with random_state=42) to:
1. Verify numerically that the Monte Carlo mean and variance of each segment's
   size match Q3's closed-form SQL formulas SUM(p) and SUM(p*(1-p)).
2. Estimate tail probabilities P(segment size >= hard_count) that require a
   Poisson-binomial distribution across worlds.
"""

import numpy as np
import pandas as pd

from src import config, db, prob_queries

N_WORLDS = 10000


def sample_possible_worlds(
    con,
    method: str = "bootstrap",
    n_worlds: int = N_WORLDS,
) -> pd.DataFrame:
    """Draw `n_worlds` possible worlds from the BID table `segment_membership`."""
    seg_order = ["Champions", "Loyal", "At-Risk", "New", "Hibernating"]
    pivot_df = (
        con.execute(
            """
            SELECT customer_id, segment, p
            FROM segment_membership
            WHERE snapshot = 'S3'
              AND method = ?
            ORDER BY customer_id, segment
            """,
            [method],
        )
        .df()
        .pivot(index="customer_id", columns="segment", values="p")[seg_order]
    )

    probs = pivot_df.to_numpy(dtype=float)
    # Normalise rows defensively so cumulative sums end at 1.0
    probs = probs / probs.sum(axis=1, keepdims=True)
    cum_probs = np.cumsum(probs, axis=1)
    cum_probs[:, -1] = 1.0

    rng = np.random.default_rng(config.RANDOM_STATE)
    n_customers, k_segs = probs.shape
    # Draw uniform (n_worlds, n_customers) and map each customer to a segment 0..K-1
    u = rng.random((n_worlds, n_customers))
    # Broadcasting: compare u[:, :, None] against cum_probs[None, :, :]
    chosen = (u[:, :, None] > cum_probs[None, :, :]).sum(axis=2)

    world_counts = np.zeros((n_worlds, k_segs), dtype=np.int32)
    for s_idx in range(k_segs):
        world_counts[:, s_idx] = (chosen == s_idx).sum(axis=1)

    q3_df = prob_queries.run_template(con, "Q3", {"method": method}).set_index("segment")

    rows = []
    for s_idx, seg_name in enumerate(seg_order):
        counts_s = world_counts[:, s_idx]
        sql_mean = float(q3_df.loc[seg_name, "expected_size"])
        sql_var = float(q3_df.loc[seg_name, "variance_independent"])
        sql_std = float(q3_df.loc[seg_name, "std_dev_independent"])
        hard_n = int(q3_df.loc[seg_name, "hard_count"])

        mc_mean = float(np.mean(counts_s))
        mc_var = float(np.var(counts_s, ddof=1))
        mc_std = float(np.std(counts_s, ddof=1))
        p_ge_hard = float(np.mean(counts_s >= hard_n))
        ci_low, ci_high = np.percentile(counts_s, [2.5, 97.5])

        rows.append({
            "method": method,
            "segment": seg_name,
            "n_worlds": n_worlds,
            "hard_count": hard_n,
            "sql_expected_size": round(sql_mean, 2),
            "mc_mean_size": round(mc_mean, 2),
            "abs_mean_diff": round(abs(mc_mean - sql_mean), 4),
            "sql_variance": round(sql_var, 2),
            "mc_variance": round(mc_var, 2),
            "sql_std_dev": round(sql_std, 2),
            "mc_std_dev": round(mc_std, 2),
            "mc_95_ci_low": int(round(ci_low)),
            "mc_95_ci_high": int(round(ci_high)),
            "prob_size_ge_hard_count": round(p_ge_hard, 4),
        })
    return pd.DataFrame(rows)


def run() -> None:
    con = db.connect_app(config.DB_PATH)
    frames = [
        sample_possible_worlds(con, method="bootstrap", n_worlds=N_WORLDS),
        sample_possible_worlds(con, method="gmm", n_worlds=N_WORLDS),
    ]
    con.close()

    out_df = pd.concat(frames, ignore_index=True)
    config.TABLES_DIR.mkdir(parents=True, exist_ok=True)
    out_df.to_csv(config.TABLES_DIR / "possible_worlds_q3_check.csv", index=False)
    print("=== Possible-Worlds Monte Carlo Verification of Q3 (10,000 worlds) ===")
    print(out_df.to_string(index=False))


if __name__ == "__main__":
    run()
